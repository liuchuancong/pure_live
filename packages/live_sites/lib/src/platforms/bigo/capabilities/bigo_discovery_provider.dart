/// Bigo's discovery feed: a slice of the one public list.
///
/// The list is a finite snapshot, not a personalised feed, and it is not
/// infinite either — a page past its ~20 rooms is empty without a request.
final class BigoDiscoveryProvider implements LiveDiscoveryProvider {
  /// Serves [site].
  BigoDiscoveryProvider({required this.site});

  /// The site this capability serves.
  final BigoSite site;

  @override
  Future<Either<LiveSiteError, LivePage<LiveRoom>>> getRecommendedRooms({LivePageRequest? request}) async {
    request ??= LivePageRequest();
    try {
      final result = await site.recommend(request.page, request.pageSize);
      return right(LivePage.of(items: result.rooms, hasMore: result.hasMore));
    } on BigoFailure catch (failure) {
      return left(failure.toLiveSiteError(bigoSiteId));
    } on Object catch (error) {
      return left(LiveSiteError.unexpected(siteId: bigoSiteId, message: '$error', cause: error));
    }
  }
}
