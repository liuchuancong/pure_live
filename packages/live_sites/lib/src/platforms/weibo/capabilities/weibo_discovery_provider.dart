/// Weibo's recommendations: the platform's snapshot
/// (`pc_recommend/list.json`), one page.
///
/// The site has no personalized feed and no native pagination; the snapshot
/// is what the watch page shows, and it ends where the list ends. A page
/// after the first is empty without a request; the request's page size is
/// not applied, as the reference never applied it.
final class WeiboDiscoveryProvider implements LiveDiscoveryProvider {
  /// Serves [site].
  WeiboDiscoveryProvider({required this.site});

  /// The site this capability serves.
  final WeiboSite site;

  @override
  Future<Either<LiveSiteError, LivePage<LiveRoom>>> getRecommendedRooms({
    LivePageRequest request = const LivePageRequest(),
  }) async {
    try {
      final page = await site.snapshot(page: request.page);
      return right(LivePage(items: page.rooms, hasMore: page.hasMore));
    } on WeiboFailure catch (failure) {
      return left(failure.toLiveSiteError(weiboSiteId));
    } on Object catch (error) {
      return left(LiveSiteError.unexpected(siteId: weiboSiteId, message: '$error', cause: error));
    }
  }
}
