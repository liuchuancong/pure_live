import 'package:equatable/equatable.dart';

import '../../../support/json.dart';

/// One subtitle track.
final class SubtitleTrack extends Equatable {
  const SubtitleTrack({
    required this.id,
    required this.language,
    this.label,
    this.uri,
    this.mimeType,
    this.isAutoGenerated = false,
    this.isDefault = false,
  });

  factory SubtitleTrack.fromJson(Map<String, Object?> json) => SubtitleTrack(
    id: requireString(json, 'id', 'subtitle_track'),
    language: requireString(json, 'language', 'subtitle_track'),
    label: json['label'] is String ? json['label']! as String : null,
    uri: json['uri'] is String ? Uri.tryParse(json['uri']! as String) : null,
    mimeType: json['mimeType'] is String ? json['mimeType']! as String : null,
    isAutoGenerated: json['isAutoGenerated'] as bool? ?? false,
    isDefault: json['isDefault'] as bool? ?? false,
  );

  /// Machine-readable language tag, as the source wrote it (BCP-47 in most cases). [label] is what the human
  /// sees, and the two differ - bilibili's tag is `zh-CN` while its menu says 中文.
  final String id;
  final String language;
  final String? label;

  /// Null means the bytes come **with the stream** (an in-band CC track) rather than from a sidecar url - the
  /// player has to know which of the two it is selecting.
  final Uri? uri;
  final String? mimeType;

  /// ASR subtitles are a different promise from authored ones, and a viewer who cannot tell has no way to
  /// forgive the mistakes.
  final bool isAutoGenerated;
  final bool isDefault;

  String get displayLabel => label?.isNotEmpty == true ? label! : language;

  bool get isSidecar => uri != null;

  Map<String, Object?> toJson() => <String, Object?>{
    'id': id,
    'language': language,
    if (label != null) 'label': label,
    if (uri != null) 'uri': uri.toString(),
    if (mimeType != null) 'mimeType': mimeType,
    if (isAutoGenerated) 'isAutoGenerated': true,
    if (isDefault) 'isDefault': true,
  };

  @override
  List<Object?> get props => <Object?>[id, language, label, uri, mimeType, isAutoGenerated, isDefault];
}
